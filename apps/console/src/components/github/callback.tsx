"use client";
import Link from "next/link";
import { useState } from "react";
import { useRouter } from "next/navigation";
import { mutate } from "@/lib/client-api";
import { Button } from "@/components/ui/button";
import { ErrorNotice } from "@/components/shared/feedback";

export function GitHubCallback({
  code,
  state,
}: {
  code?: string;
  state?: string;
}) {
  const router = useRouter(),
    [busy, setBusy] = useState(false),
    [error, setError] = useState<string | null>(null);
  async function complete() {
    setBusy(true);
    setError(null);
    try {
      if (state)
        await mutate("/v1/github/setup/complete", {
          state,
          purpose: code ? "manifest" : "installation",
          code: code || "",
        });
      else await mutate("/v1/github/sync");
      router.replace("/settings/github");
      router.refresh();
    } catch (error) {
      setError((error as Error).message);
      setBusy(false);
    }
  }
  return (
    <>
      <div className="page-heading">
        <div>
          <h1>Complete GitHub setup</h1>
          <p>
            {code
              ? "Save the App credentials generated by GitHub, then choose its repositories."
              : "Synchronize GitHub’s current repository selection with this installation."}
          </p>
        </div>
      </div>
      <section className="panel flex max-w-2xl flex-col gap-5 p-5">
        <p>
          {code
            ? "Only the administrator who started registration can complete this exchange. GitHub’s generated private key stays on this installation."
            : "Repository access comes from the App’s current GitHub installation. A callback URL alone cannot grant delivery access."}
        </p>
        <ErrorNotice message={error} />
        <div className="flex flex-wrap items-center gap-4">
          <Button disabled={busy} onClick={complete}>
            {busy
              ? "Completing setup"
              : code
                ? "Finish App registration"
                : "Synchronize repositories"}
          </Button>
          <Link href="/settings/github">Back to GitHub delivery</Link>
        </div>
      </section>
    </>
  );
}
